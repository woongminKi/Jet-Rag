/**
 * `doc_id` UUID 가드 — **사용자가 만들 수 있던 500 을 없앤 자리**를 고정한다.
 *
 * 원본(Railway)도 같은 500 을 낸다(실측 2026-09-07). 이관 중에는 맞춰 뒀지만
 * `/documents/*` 읽기가 100% Edge 가 된 뒤 고쳤다 — work-log §51.
 */

import { assertEquals } from "@std/assert";

import { isUuid } from "./uuid_guard.ts";

Deno.test("UUID 만 통과한다", () => {
  // 실제로 500 을 만들던 입력들 — 주소창에 아무거나 넣으면 나온다.
  for (
    const bad of [
      "url", // §47 에서 폐기된 `POST /documents/url` 의 잔재로 실제로 밟힌 경로
      "not-a-uuid",
      "12345",
      "abc-def",
      "",
      "00000000-0000-4000-8000-00000000000", // 한 자 모자람
      "00000000-0000-4000-8000-0000000000000", // 한 자 많음
      "00000000_0000_4000_8000_000000000000", // 하이픈 대신 밑줄
      "0000000g-0000-4000-8000-000000000000", // 16진수 아님
      " 00000000-0000-4000-8000-000000000000", // 앞 공백
      "00000000-0000-4000-8000-000000000000 ", // 뒤 공백
    ]
  ) {
    assertEquals(isUuid(bad), false, `허용되면 안 된다: ${JSON.stringify(bad)}`);
  }
});

Deno.test("실제 doc_id 형태를 막지 않는다", () => {
  for (
    const ok of [
      "11111111-1111-4111-8111-111111111111",
      "2e083cb0-0000-4000-8000-000000000000",
      "AAAAAAAA-BBBB-CCCC-DDDD-EEEEEEEEEEEE", // 대문자
      "00000000-0000-0000-0000-000000000000", // nil UUID — Postgres 가 받는다
    ]
  ) {
    assertEquals(isUuid(ok), true, `막으면 안 된다: ${ok}`);
  }
});
